// Builds src/TRStudio.Engine/GpuCatalog.g.cs from OpenRGB's graphics-card detector lines.
//
// Usage: dotnet run --project tools/GpuCatalogGen [openrgb-src] [output.cs]
// Defaults: E:\LLM\Forking\openrgb-src and src/TRStudio.Engine/GpuCatalog.g.cs under the repo root.
//
// It reads every REGISTER_I2C_PCI_DETECTOR(name, fn, ven, dev, subven, subdev, addr) line under
// Controllers/, resolves the id macros through pci_ids/pci_ids.h and the address macros through the
// #defines and enum values in that controller's own folder, and fails if any name can't be resolved.
// The driver is the folder that holds the detector file (e.g. GalaxGPUController).

using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

var repo = FindRepoRoot(AppContext.BaseDirectory) ?? Directory.GetCurrentDirectory();
var openrgb = args.Length > 0 ? args[0] : @"E:\LLM\Forking\openrgb-src";
var output = args.Length > 1 ? args[1] : Path.Combine(repo, "src", "TRStudio.Engine", "GpuCatalog.g.cs");

var controllers = Path.Combine(openrgb, "Controllers");
var pciIds = Path.Combine(openrgb, "pci_ids", "pci_ids.h");
if (!Directory.Exists(controllers) || !File.Exists(pciIds))
{
    Console.Error.WriteLine($"OpenRGB source not found at {openrgb}");
    return 1;
}

var defineRx = new Regex(@"^\s*#\s*define\s+(\w+)\s+(0[xX][0-9A-Fa-f]+|\d+)\b", RegexOptions.Multiline);
var enumRx = new Regex(@"^\s*(\w+)\s*=\s*(0[xX][0-9A-Fa-f]+|\d+)\s*,?", RegexOptions.Multiline);
var detectorRx = new Regex(
    @"\bREGISTER_I2C_PCI_DETECTOR(_DISABLED)?\s*\(\s*""((?:[^""\\]|\\.)*)""\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*\)");

var pciSymbols = ReadSymbols(StripComments(File.ReadAllText(pciIds)), defineRx, null);

var entries = new List<Entry>();
var errors = new List<string>();
var disabled = 0;
foreach (var file in Directory.EnumerateFiles(controllers, "*.cpp", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
{
    var code = StripComments(File.ReadAllText(file));
    var matches = detectorRx.Matches(code);
    if (matches.Count == 0) continue;

    var folder = Path.GetDirectoryName(file)!;
    var driver = Path.GetFileName(folder);
    var local = new Dictionary<string, int>();
    foreach (var src in Directory.EnumerateFiles(folder, "*.*", SearchOption.AllDirectories)
                 .Where(f => f.EndsWith(".h") || f.EndsWith(".cpp")))
        ReadSymbols(StripComments(File.ReadAllText(src)), defineRx, enumRx, local);

    foreach (Match m in matches)
    {
        if (m.Groups[1].Success) { disabled++; continue; }
        var name = Regex.Unescape(m.Groups[2].Value).Trim();
        int? Resolve(string token)
        {
            if (TryNumber(token, out var n)) return n;
            if (pciSymbols.TryGetValue(token, out n)) return n;
            if (local.TryGetValue(token, out n)) return n;
            errors.Add($"{Path.GetRelativePath(openrgb, file)}: \"{name}\": can't resolve {token}");
            return null;
        }
        var ids = new[] { 4, 5, 6, 7, 8 }.Select(i => Resolve(m.Groups[i].Value)).ToArray();
        if (ids.Any(v => v is null)) continue;
        entries.Add(new Entry(name, (ushort)ids[0]!, (ushort)ids[1]!, (ushort)ids[2]!, (ushort)ids[3]!, (byte)ids[4]!, driver, m.Groups[3].Value));
    }
}

if (errors.Count > 0)
{
    foreach (var e in errors) Console.Error.WriteLine(e);
    return 1;
}

var unique = new List<Entry>();
var seen = new HashSet<Entry>();
foreach (var e in entries)
    if (seen.Add(e)) unique.Add(e);
    else Console.WriteLine($"Dropped exact duplicate: {e.Name} ({e.Driver})");

// Cards OpenRGB doesn't list yet, kept here so a rebuild keeps them.
var extra = new (Entry Entry, string Note)[]
{
    (new Entry("GALAX GeForce RTX 4070 EX Gamer", 0x10DE, 0x2786, 0x10DE, 0x1875, 0x50, "GalaxGPUController", "DetectGalaxGPUControllers"),
     "Not in OpenRGB. Ids from GALAX Xtreme Tuner's files; chip found at 0x50 (identity 02 01, Galax v2 layout) and a color write confirmed on the real card, Nov 12, 2026."),
};

File.WriteAllText(output, Render(unique, extra), new UTF8Encoding(false));
Console.WriteLine($"Wrote {unique.Count} OpenRGB entries + {extra.Length} extra to {output} ({disabled} disabled detectors skipped)");
return 0;

static string Render(List<Entry> entries, (Entry Entry, string Note)[] extra)
{
    var sb = new StringBuilder();
    sb.Append("""
        // SPDX-License-Identifier: GPL-2.0-or-later
        //
        // <auto-generated> by tools/GpuCatalogGen. Don't edit by hand: change the generator and run it again.
        //
        // Graphics cards with RGB lighting reachable over the card's I2C bus. The card names, PCI ids and I2C
        // addresses come from the OpenRGB project (https://gitlab.com/CalcProgrammer1/OpenRGB): the
        // REGISTER_I2C_PCI_DETECTOR lines in Controllers/*/*Detect.cpp and the ids in pci_ids/pci_ids.h,
        // by Adam Honse (CalcProgrammer1) and the OpenRGB contributors, licensed GPL-2.0-or-later.

        namespace TRStudio.Engine;

        /// <summary>One graphics card a lighting driver may talk to: all four PCI ids must match exactly.</summary>
        /// <param name="Driver">The OpenRGB controller folder the card belongs to, e.g. GalaxGPUController.</param>
        /// <param name="Detector">OpenRGB's detect function for the card, which tells variants of one driver apart (such as a Gigabyte Blackwell layout).</param>
        public sealed record GpuCatalogEntry(string Name, ushort Vendor, ushort Device, ushort SubVendor, ushort SubDevice, byte Address, string Driver, string Detector);

        public static class GpuCatalog
        {
            /// <summary>Every known card, in OpenRGB's order, then the cards added here.</summary>
            public static readonly IReadOnlyList<GpuCatalogEntry> All =
            [

        """);
    string Line(Entry e) =>
        $"        new({Quote(e.Name)}, 0x{e.Vendor:X4}, 0x{e.Device:X4}, 0x{e.SubVendor:X4}, 0x{e.SubDevice:X4}, 0x{e.Address:X2}, {Quote(e.Driver)}, {Quote(e.Detector)}),\n";
    foreach (var e in entries) sb.Append(Line(e));
    sb.Append("\n        // Added by TR Studio, not from OpenRGB.\n");
    foreach (var (e, note) in extra)
    {
        sb.Append("        // ").Append(note).Append('\n');
        sb.Append(Line(e));
    }
    sb.Append("""
            ];

            static readonly ILookup<(ushort, ushort, ushort, ushort), GpuCatalogEntry> ByIds =
                All.ToLookup(e => (e.Vendor, e.Device, e.SubVendor, e.SubDevice));

            /// <summary>Every entry whose four PCI ids all match exactly; empty for an unknown card.</summary>
            public static IReadOnlyList<GpuCatalogEntry> Find(ushort vendor, ushort device, ushort subVendor, ushort subDevice) =>
                ByIds[(vendor, device, subVendor, subDevice)].ToList();
        }

        """);
    return sb.ToString().Replace("\r\n", "\n");
}

static string Quote(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

static bool TryNumber(string token, out int value)
{
    if (token.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
        return int.TryParse(token.AsSpan(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out value);
    return int.TryParse(token, NumberStyles.None, CultureInfo.InvariantCulture, out value);
}

static Dictionary<string, int> ReadSymbols(string code, Regex defines, Regex? enums, Dictionary<string, int>? into = null)
{
    into ??= new Dictionary<string, int>();
    foreach (var rx in new[] { defines, enums })
    {
        if (rx is null) continue;
        foreach (Match m in rx.Matches(code))
            if (TryNumber(m.Groups[2].Value, out var v)) into.TryAdd(m.Groups[1].Value, v);
    }
    return into;
}

// Removes // and /* */ comments, leaving string literals alone, so commented-out detectors are skipped.
static string StripComments(string code)
{
    var sb = new StringBuilder(code.Length);
    for (var i = 0; i < code.Length; i++)
    {
        var c = code[i];
        if (c == '"')
        {
            var j = i + 1;
            while (j < code.Length && code[j] != '"' && code[j] != '\n') j += code[j] == '\\' ? 2 : 1;
            j = Math.Min(j, code.Length - 1);
            sb.Append(code, i, j - i + 1);
            i = j;
        }
        else if (c == '/' && i + 1 < code.Length && code[i + 1] == '/')
        {
            while (i < code.Length && code[i] != '\n') i++;
            sb.Append('\n');
        }
        else if (c == '/' && i + 1 < code.Length && code[i + 1] == '*')
        {
            var end = code.IndexOf("*/", i + 2, StringComparison.Ordinal);
            i = end < 0 ? code.Length : end + 1;
            sb.Append(' ');
        }
        else sb.Append(c);
    }
    return sb.ToString();
}

static string? FindRepoRoot(string start)
{
    for (var dir = new DirectoryInfo(start); dir is not null; dir = dir.Parent)
        if (File.Exists(Path.Combine(dir.FullName, "TRStudio.sln"))) return dir.FullName;
    return null;
}

record Entry(string Name, ushort Vendor, ushort Device, ushort SubVendor, ushort SubDevice, byte Address, string Driver, string Detector);
